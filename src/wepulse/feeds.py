from datetime import datetime, timezone
from email.utils import format_datetime
from xml.etree.ElementTree import Element, SubElement, tostring


def rss_xml(title: str, articles: list[dict], base_url: str = "") -> str:
    rss = Element("rss", version="2.0")
    channel = SubElement(rss, "channel")
    SubElement(channel, "title").text = title
    SubElement(channel, "link").text = base_url
    SubElement(channel, "description").text = f"{title} generated by WePulse"
    SubElement(channel, "lastBuildDate").text = format_datetime(datetime.now(timezone.utc))
    for article in articles:
        item = SubElement(channel, "item")
        SubElement(item, "title").text = article["title"]
        SubElement(item, "link").text = article["url"]
        SubElement(item, "guid", isPermaLink="false").text = f"{article['account_id']}:{article['external_id']}"
        published = datetime.fromisoformat(article["published_at"])
        SubElement(item, "pubDate").text = format_datetime(published)
        SubElement(item, "description").text = article.get("summary", "")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + tostring(rss, encoding="unicode")
